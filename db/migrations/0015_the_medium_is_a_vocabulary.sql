CREATE FUNCTION public.a_pass_through_an_object_went_by_a_medium_that_can() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
declare
  through_an_object boolean;
begin
  -- A pass through no object is every digital pass, every borrowed one and every one known
  -- only from a history — the ordinary case, and there is nothing here to hold it to.
  if new.volume_id is null then
    return null;
  end if;

  select m.goes_through_an_object into through_an_object
    from medium m where m.id = new.medium;

  -- A medium this library does not know is `pass_medium_exists`' refusal and not this one, so
  -- the row is simply absent here and there is nothing left for this rule to say about it.
  if through_an_object is null or through_an_object then
    return null;
  end if;

  raise exception 'that medium does not go through an object'
    using errcode = 'check_violation',
          constraint = 'pass_through_an_object_went_by_a_medium_that_can';

  return null;
end;
$$;--> statement-breakpoint

COMMENT ON FUNCTION public.a_pass_through_an_object_went_by_a_medium_that_can() IS 'A Pass naming a Volume went by a medium that can go through an object, which today is paper alone (#61, ADR-0022). It is what the check constraint pass_digital_went_through_no_volume said while the list of media was closed; a check constraint cannot read the vocabulary row, so the rule is restated across the two tables.';--> statement-breakpoint

CREATE TRIGGER pass_through_an_object_went_by_a_medium_that_can
    AFTER INSERT OR UPDATE OF medium, volume_id ON public.pass
    FOR EACH ROW EXECUTE FUNCTION public.a_pass_through_an_object_went_by_a_medium_that_can();--> statement-breakpoint

