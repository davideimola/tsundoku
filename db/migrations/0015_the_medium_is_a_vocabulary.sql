-- The medium is a vocabulary, and only paper goes through an object (#61, ADR-0022).
--
-- `pass.medium` was two values written into a check constraint. It becomes a **table of
-- data**, beside Type, Binding, Provenance and credit_role: the console a game was played on
-- is a medium standing on the same axis as paper and digital, and a console released next
-- year is an insert rather than a migration.
--
-- The rule the old constraint carried moves with it. `pass_digital_went_through_no_volume`
-- said *a pass through a Volume is a pass on paper*, by naming the one value that was not
-- allowed to go through an object. With a list that grows, that sentence cannot live in a
-- constraint over values: each medium **declares whether it can go through an object**, in
-- `goes_through_an_object`, and only paper does. No console can, which is the same fact the
-- old rule stated, said in a way that survives a fourth console.
--
-- **Nothing about this library changes today.** Two rows are seeded and they are the two
-- values the constraint held, carrying the flag it implied; every Pass already standing
-- points at one of them, and the invariant refuses exactly what it refused before. What
-- changes is where the list lives.
--
-- The order of the statements is the whole of the migration's correctness, and it is one
-- transaction: the rows exist before the foreign key that points at them, and the invariant
-- is put back before the check it replaces is taken away — so there is no instant, even
-- inside the transaction, at which a pass through an object could be recorded by a medium
-- that does not go through one.
--
-- **The invariant is a trigger** rather than a check, because a check constraint cannot read
-- another table and whether *this* medium goes through an object is a fact on the vocabulary
-- row. Cross-table invariants in this schema are triggers already —
-- `volume_holds_one_position()` since 0000, `an_instalment_lies_inside_the_work()` since 0007
-- — so this follows the house style rather than introducing one (ADR-0009, ADR-0017). It
-- raises with a constraint name, and `src/core/verbs/pass.ts` turns that name into the prose
-- the owner reads.
--
-- It fires where a **Pass** is written, which is where the old check fired and every write
-- there is. The vocabulary's own side is not guarded: a medium *added* cannot invalidate
-- anything, and taking the flag off a medium that passes have already gone through objects by
-- would — `the_work_still_holds_what_was_read()` in 0012 is the shape that rule would take.
-- Nothing writes that column today and no ticket has asked for a gesture that does, so it is
-- reported rather than invented here (#61).
--
-- Generated by `drizzle-kit generate` and then hand-finished: the seeded rows, the order
-- above, the function, its trigger and every `comment on` are the part Drizzle does not
-- write (ADR-0009).

CREATE TABLE "medium" (
	"id" text PRIMARY KEY NOT NULL,
	"name" text NOT NULL,
	"display_order" integer NOT NULL,
	"goes_through_an_object" boolean NOT NULL,
	CONSTRAINT "medium_name_key" UNIQUE("name"),
	CONSTRAINT "medium_display_order_key" UNIQUE("display_order"),
	CONSTRAINT "medium_id_is_a_slug" CHECK (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'::text),
	CONSTRAINT "medium_name_is_not_blank" CHECK ((name = btrim(name)) AND (name <> ''::text)),
	CONSTRAINT "medium_display_order_is_positive" CHECK (display_order > 0)
);
