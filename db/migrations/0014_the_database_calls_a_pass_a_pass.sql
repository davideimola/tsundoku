-- The not-null constraints, which Postgres names after the table and Drizzle does not model.
-- A loop rather than a list of renames because the names are the server's and not ours: where
-- a server does not name them at all there is nothing to find, and this says so by finding
-- nothing instead of failing on a name that was never there.
DO $$
DECLARE named record;
BEGIN
  FOR named IN
    SELECT conname FROM pg_constraint
     WHERE conrelid = 'public.pass'::regclass AND contype = 'n' AND conname LIKE 'reading\_%'
  LOOP
    EXECUTE format('ALTER TABLE public.pass RENAME CONSTRAINT %I TO %I',
                   named.conname, 'pass_' || substring(named.conname from 9));
  END LOOP;

  FOR named IN
    SELECT conname FROM pg_constraint
     WHERE conrelid = 'public.pile_pin'::regclass AND contype = 'n'
       AND conname LIKE 'reading\_list\_pin\_%'
  LOOP
    EXECUTE format('ALTER TABLE public.pile_pin RENAME CONSTRAINT %I TO %I',
                   named.conname, 'pile_pin_' || substring(named.conname from 18));
  END LOOP;
END $$;--> statement-breakpoint

-- The trigger, and the two functions that name the table in their bodies. PL/pgSQL resolves a
-- table name when the function runs and not when it is created, so a rename that stopped at
-- the catalogue would leave both of these raising `relation "reading" does not exist` the next
-- time anybody wrote an Instalment. They are replaced whole rather than edited, which is what
-- ADR-0009 said would happen to any Postgres past the DSL.

ALTER TRIGGER "reading_at_instalment_lies_inside_the_work" ON "pass" RENAME TO "pass_at_instalment_lies_inside_the_work";--> statement-breakpoint

CREATE OR REPLACE FUNCTION public.an_instalment_lies_inside_the_work() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
declare
  declared integer;
  reached  integer;
  covered  integer;
begin
  select s.instalments into declared from story s where s.id = new.story_id;

  -- Two branches rather than one expression, because PL/pgSQL resolves the fields of `new`
  -- against whichever row type fired the trigger: `new.covers_to` written beside
  -- `new.at_instalment` fails on the `pass` trigger even where it is never reached. The
  -- same reason 0000 splits `volume_holds_one_position()`.
  if tg_table_name = 'pass' then
    reached := new.at_instalment;

    -- Nothing said about how far it got, which is the ordinary pass.
    if reached is null then
      return null;
    end if;

    if declared is null then
      raise exception 'that Story has no Instalments to be at'
        using errcode = 'check_violation',
              constraint = 'pass_at_instalment_needs_a_serialized_story';
    end if;

    if reached > declared then
      raise exception 'that pass got further than the work goes'
        using errcode = 'check_violation',
              constraint = 'pass_at_instalment_is_within_the_work';
    end if;
  else
    covered := new.covers_to;

    -- No range written by hand, so the range follows the object's position in its line.
    if covered is null then
      return null;
    end if;

    if declared is null then
      raise exception 'that Story has no Instalments to cover'
        using errcode = 'check_violation',
              constraint = 'volume_story_cover_needs_a_serialized_story';
    end if;

    if covered > declared then
      raise exception 'that object covers past the end of the work'
        using errcode = 'check_violation',
              constraint = 'volume_story_cover_lies_inside_the_work';
    end if;
  end if;

  return null;
end;
$$;--> statement-breakpoint

CREATE OR REPLACE FUNCTION public.the_work_still_holds_what_was_read() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  if new.instalments is not distinct from old.instalments then
    return null;
  end if;

  -- Shortening a work, or taking its numbering away altogether, is refused while a pass or
  -- an object stands beyond the new end. Otherwise the invariant above would hold only at
  -- the moment it was written, and *seven of five* would be reachable by editing the five.
  if exists (
    select 1 from pass r
     where r.story_id = new.id
       and r.at_instalment is not null
       and (new.instalments is null or r.at_instalment > new.instalments)
  ) then
    raise exception 'a pass through it got further than that'
      using errcode = 'check_violation',
            constraint = 'story_instalments_still_hold_what_was_read';
  end if;

  if exists (
    select 1 from volume_story vs
     where vs.story_id = new.id
       and vs.covers_to is not null
       and (new.instalments is null or vs.covers_to > new.instalments)
  ) then
    raise exception 'an object covers further than that'
      using errcode = 'check_violation',
            constraint = 'story_instalments_still_hold_what_is_covered';
  end if;

  return null;
end;
$$;--> statement-breakpoint

