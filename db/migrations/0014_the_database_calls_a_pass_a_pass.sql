-- **The database calls a pass a Pass**, and the Reading list the Pile (#56, #55).
--
-- `CONTEXT.md` had stopped using the old word before this migration was written — it says
-- *a pass* four times inside the entry that used to define a Reading — because a Reading is
-- *one act of reading a Story* and a videogame is not read. The glossary now says **Pass**,
-- and **the Pile** for what the owner takes on next, and this is the schema catching up
-- (ADR-0021).
--
-- **This is the expand half of an expand-contract rename**, and the half of it a database can
-- do. `db/schema.ts` re-exports `reading` and `readingListPin` as aliases of `pass` and
-- `pilePin`, so anything typed from the schema module goes on describing the same rows.
-- Nothing else does: the queries above `db/` are SQL text and not a builder (ADR-0009), so
-- they name these tables, `rating.reading_id` and half these constraints in strings, which no
-- alias reaches. **Until the contract step (#57) renames them, the repository does not run
-- against this schema.** That is the shape of the rename and not an accident of this file —
-- there is no version of it in which a table has both names at once.
--
-- **Renamed rather than recreated, everywhere it could be.** `drizzle-kit generate` writes a
-- rename of the two tables and the one column and then drops and re-adds every constraint and
-- index whose name changed with them. The end state is the same and the cost is not: a dropped
-- and re-added check or foreign key is revalidated against the whole table, and for the length
-- of one statement the invariant is not there at all. `ALTER TABLE ... RENAME CONSTRAINT` and
-- `ALTER INDEX ... RENAME` are catalogue edits — no rewrite, no revalidation, no window. The
-- generated drop/add pairs were replaced by them; nothing else about the file's end state
-- differs, so the snapshot Drizzle wrote beside it is still the description the next diff is
-- taken against.
--
-- **Production holds real data and none of it moves.** A rename in Postgres is atomic and
-- touches no row: 96 Stories, 45 passes and 40 Ratings are the same rows under the new words,
-- with no backfill, no copy and no moment where a record is missing.
--
-- The applied migrations behind this one go on saying `reading` for ever. They are
-- forward-only and hashed and are never edited; what they say is what was true when they ran.
--
-- **The journal's `when` was moved forward**, which is the exception `0010` took and for its
-- reason: `0012` reserved a round timestamp a day ahead of the clock, so the honest one the
-- generator wrote here sorted behind a migration that runs before it. The tag and the order
-- are the generator's; only the timestamp was corrected, so that the moment Drizzle applies
-- by agrees with the order the journal lists.
--
-- Generated by `drizzle-kit generate` and then hand-finished, which here is four things: the
-- renames above, the not-null constraints Drizzle does not model, the two PL/pgSQL functions
-- that name the table in their bodies, and every `comment on`, which is where this schema
-- documents itself (ADR-0009).

