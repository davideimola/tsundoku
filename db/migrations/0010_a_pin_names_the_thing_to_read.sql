-- **A pin names the thing to read**, and no longer the source it came from (#40, #34).
--
-- The Reading list becomes two halves — a head the owner pinned, in pin order, and a
-- reserve that composes itself and is deliberately unordered — and the pin is what
-- separates them. That is only sayable if a pin points at an *entry*, and an entry is now
-- keyed by the thing to read: a **Story**, or a **position of a Series**.
--
-- What it replaces, and why the old subject could not stay. A pin named a Path or a Series,
-- and a route contributed exactly one stop, so *three Marvel stories and then a DC one* had
-- nowhere to be written down: pinning Marvel pinned whatever Marvel happened to be offering,
-- and the second and third stop of that route could not be reached at all. It also could not
-- survive the dedup this slice brings — one Story is one row however many reasons put it
-- there, so a row that is wanted *and* on two routes has three sources and could not be
-- addressed by any one of them.
--
--   * **`story_id`** — the narrative to read. One pin per Story, because one Story is one
--     row; cascading, because a Story struck from the library has no place left on a list
--     (ADR-0015).
--   * **`series_id` + `series_position`** — the shopping half, which names an *object* and no
--     narrative (ADR-0001), so the line alone does not identify it: the entry is *Death Note
--     Black Edition 2* and not *Death Note Black Edition*. One pin per position of a line.
--   * **exactly one of the two, and Postgres says so** rather than an `if` in a verb. A
--     Series pin without a position is not a subject at all, which is the second check; the
--     third is that a position is a place in a line, counted from one.
--
-- `path_id` goes, and the pins standing on it are **carried across rather than dropped**: the
-- owner does nothing, and what they pinned yesterday is still at the front tomorrow. A pin on
-- a Path becomes a pin on the Story that route was offering — its first stop with no Reading
-- at all, which is what `to-read` means in `src/core/queries/story.ts` — and a pin on a Series
-- gains the position that line was offering, the first the house does not hold. A pin whose
-- subject had nothing left to offer is deleted, and loses nothing: a route walked out or put
-- aside contributed no entry yesterday either.
--
-- Generated by `drizzle-kit generate` and then hand-finished, which here is three things: the
-- backfill in the middle, which Drizzle cannot know about, the `comment on` statements, which
-- are where this schema documents itself (ADR-0009), and the number. The **number is the same
-- exception #34's other slices took** (README): several slices of one tracker were written in
-- parallel worktrees off one base, and the owner reserved a prefix to each so that two
-- generators could not write `0010_` at once. The generator produced this file as
-- `0010_melodic_ezekiel`; the tag was renamed for what it does, and its `when` set after
-- `0009`'s so that the timestamp Drizzle applies by agrees with the order the journal lists.

