-- The pins the owner already has, moved onto the new subject. Between the columns arriving
-- and the old one leaving, which is the only moment both subjects exist.

-- A pin on a Path becomes a pin on the Story that route was offering: its first stop nothing
-- has been read of, in the owner's own order.
UPDATE reading_list_pin p
   SET story_id = (
     SELECT i.story_id
       FROM path_item i
      WHERE i.path_id = p.path_id
        AND NOT EXISTS (SELECT 1 FROM reading r WHERE r.story_id = i.story_id)
      ORDER BY i.position
      LIMIT 1
   )
 WHERE p.path_id IS NOT NULL;--> statement-breakpoint

-- A pin on a Series gains the position that line was offering: the first the house does not
-- hold, which is what the ledger calls missing.
UPDATE reading_list_pin p
   SET series_position = (
     SELECT n
       FROM generate_series(1, s.published_count) AS n
      WHERE NOT EXISTS (
        SELECT 1
          FROM volume v
         WHERE v.series_id = s.id
           AND v.series_number = n
           AND EXISTS (SELECT 1 FROM acquisition a
                        WHERE a.volume_id = v.id AND a.released_on IS NULL)
      )
      ORDER BY n
      LIMIT 1
   )
  FROM series s
 WHERE s.id = p.series_id;--> statement-breakpoint

-- A pin whose subject had nothing to offer goes. It contributed no entry yesterday either —
-- the route is walked out or put aside, or the line is complete — so nothing the owner could
-- see is lost with it.
DELETE FROM reading_list_pin WHERE path_id IS NOT NULL AND story_id IS NULL;--> statement-breakpoint
DELETE FROM reading_list_pin WHERE series_id IS NOT NULL AND series_position IS NULL;--> statement-breakpoint

-- Two routes can offer the same Story, and one Story is one row now: the newer pin is the
-- more recent decision and it is the one that stands.
DELETE FROM reading_list_pin p
 USING reading_list_pin q
 WHERE p.story_id IS NOT NULL
   AND p.story_id = q.story_id
   AND (q.pinned_at > p.pinned_at OR (q.pinned_at = p.pinned_at AND q.ctid > p.ctid));--> statement-breakpoint

